def resolve_language(code: str | None) -> str:
    """Narrow whatever Telegram (or our own settings) reports to a language we
    actually speak."""
    short = (code or "").split("-")[0].lower()
    return short if short in LANGUAGES else DEFAULT_LANGUAGE


def t(language: str | None, key: str) -> str:
    lang = resolve_language(language)
    return _COPY[lang][key]
